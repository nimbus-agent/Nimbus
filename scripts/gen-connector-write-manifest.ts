#!/usr/bin/env bun
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

import { CHATOPS_POST_TOOL_IDS } from "../packages/gateway/src/chatops/transport/connector-post.ts";
import {
  installedConnectorsPackageRoot,
  readConnectorPackageSources,
  scanWriteToolRegistrations,
  type WriteToolScan,
} from "../packages/gateway/src/connectors/testing/connector-write-registrations.ts";
import { TRIBAL_KB_WRITE_TOOL_IDS } from "../packages/gateway/src/tribal/tribal-write-gate.ts";

const REPO_ROOT = resolve(import.meta.dir, "..");
const OUT = join(
  REPO_ROOT,
  "packages",
  "gateway",
  "src",
  "connectors",
  "connector-writes",
  "manifest.generated.ts",
);

const LINE_WIDTH = 100;

/** One manifest entry, laid out the way Biome leaves it (broken over lines past the line width). */
function renderEntry(toolId: string, connector: string): string {
  const one = `  { toolId: ${JSON.stringify(toolId)}, connector: ${JSON.stringify(connector)} },`;
  if (one.length <= LINE_WIDTH) return one;
  return [
    "  {",
    `    toolId: ${JSON.stringify(toolId)},`,
    `    connector: ${JSON.stringify(connector)},`,
    "  },",
  ].join("\n");
}

/**
 * The full text of `manifest.generated.ts` for a scan of the installed connectors package: every
 * registered write, less the gate-confined ids (static D17/D19 keep those out of any other file),
 * sorted by tool id. Pure. Throws when the scan has violations, so a write the scan cannot follow
 * can never be silently left out of the manifest.
 */
export function renderConnectorWriteManifest(scan: WriteToolScan): string {
  if (scan.violations.length > 0) {
    const detail = scan.violations.map((v) => `${v.file}:${v.line} ${v.reason}`).join("\n");
    throw new Error(`the connector write scan has violations:\n${detail}`);
  }
  const byId = new Map<string, string>();
  for (const r of scan.registrations) {
    if (CHATOPS_POST_TOOL_IDS.has(r.id) || TRIBAL_KB_WRITE_TOOL_IDS.has(r.id)) continue;
    byId.set(r.id, r.origin.split("/")[1] ?? "");
  }
  const entries = [...byId.entries()]
    .sort((a, b) => a[0].localeCompare(b[0]))
    .map(([toolId, connector]) => renderEntry(toolId, connector))
    .join("\n");
  return `// GENERATED by scripts/gen-connector-write-manifest.ts — do not edit by hand.
// Re-run: bun run gen:connector-write-manifest
//
// Every tool the installed @nimbus-dev/connectors package registers as a write, with the connector
// that owns it. The gate-confined ids are left out (static D17/D19). The sync test
// (manifest.sync.test.ts) ties this file to the row table and to the package.

export interface ConnectorWriteRegistration {
  readonly toolId: string;
  readonly connector: string;
}

export const CONNECTOR_WRITE_MANIFEST: readonly ConnectorWriteRegistration[] = [
${entries}
];
`;
}

if (import.meta.main) {
  const scan = scanWriteToolRegistrations(
    readConnectorPackageSources(installedConnectorsPackageRoot()),
  );
  const text = renderConnectorWriteManifest(scan);
  writeFileSync(OUT, text);
  console.log(
    `wrote ${OUT} with ${text.split("\n").filter((l) => l.includes('toolId: "')).length} writes`,
  );
}
