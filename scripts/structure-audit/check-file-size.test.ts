import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { countLines, isCounted, judge, LIMIT, lowered, measure } from "./check-file-size.ts";
import { auditOutputPath } from "./lib.ts";

describe("countLines", () => {
  test("counts like wc -l, plus an unterminated last line", () => {
    expect(countLines("")).toBe(0);
    expect(countLines("a\n")).toBe(1);
    expect(countLines("a\nb")).toBe(2);
    expect(countLines("a\r\nb\r\n")).toBe(2);
  });
});

describe("isCounted", () => {
  test("source and tests under packages/ and scripts/ only", () => {
    expect(isCounted("packages/gateway/src/x.ts", "")).toBe(true);
    expect(isCounted("packages/ui/src/x.tsx", "")).toBe(true);
    expect(isCounted("packages/ui/src-tauri/src/x.rs", "")).toBe(true);
    expect(isCounted("scripts/a/b.test.ts", "")).toBe(true);
    expect(isCounted("docs/x.ts", "")).toBe(false);
    expect(isCounted("packages/gateway/src/x.json", "")).toBe(false);
    expect(isCounted("packages/gateway/src/x.d.ts", "")).toBe(false);
    expect(isCounted("packages/github-actions/a/dist/index.js", "")).toBe(false);
  });

  test("a generated file is not counted", () => {
    expect(isCounted("packages/gateway/src/x.ts", "// GENERATED by scripts/gen.ts")).toBe(false);
  });
});

describe("judge", () => {
  const big = LIMIT + 100;

  test("a new file at the limit fails; one line under passes", () => {
    const v = judge(
      [
        { path: "a.ts", lines: LIMIT },
        { path: "b.ts", lines: LIMIT - 1 },
      ],
      {},
    );
    expect(v.tooLarge.map((f) => f.path)).toEqual(["a.ts"]);
  });

  test("a baseline file that grows by one line fails", () => {
    const v = judge([{ path: "a.ts", lines: big + 1 }], { "a.ts": big });
    expect(v.grew).toEqual([{ path: "a.ts", lines: big + 1, baseline: big }]);
    expect(v.tooLarge).toEqual([]);
  });

  test("an unchanged baseline file passes", () => {
    const v = judge([{ path: "a.ts", lines: big }], { "a.ts": big });
    expect(v).toEqual({ tooLarge: [], grew: [], stale: [] });
  });

  test("a shrunk or deleted baseline file is stale", () => {
    const v = judge([{ path: "a.ts", lines: big - 1 }], { "a.ts": big, "gone.ts": big });
    expect(v.stale.map((f) => [f.path, f.lines])).toEqual([
      ["a.ts", big - 1],
      ["gone.ts", 0],
    ]);
  });

  test("a renamed baseline file reads as new and fails", () => {
    const v = judge([{ path: "b.ts", lines: big }], { "a.ts": big });
    expect(v.tooLarge.map((f) => f.path)).toEqual(["b.ts"]);
    expect(v.stale.map((f) => f.path)).toEqual(["a.ts"]);
  });
});

describe("lowered", () => {
  test("only lowers: shrunk entries follow, small and gone ones leave, nothing is raised or added", () => {
    const next = lowered(
      [
        { path: "shrunk.ts", lines: 700 },
        { path: "small.ts", lines: 100 },
        { path: "grew.ts", lines: 900 },
        { path: "new.ts", lines: 900 },
      ],
      { "shrunk.ts": 800, "small.ts": 800, "grew.ts": 800, "gone.ts": 800 },
    );
    expect(next).toEqual({ "grew.ts": 800, "shrunk.ts": 700 });
  });
});

describe("the committed baseline", () => {
  test("matches the tree exactly", () => {
    const { files } = JSON.parse(
      readFileSync(auditOutputPath("file-size-baseline.json"), "utf8"),
    ) as {
      files: Record<string, number>;
    };
    expect(judge(measure(), files)).toEqual({ tooLarge: [], grew: [], stale: [] });
  });
});

describe("--init", () => {
  test("refuses to replace an existing baseline (it would accept growth)", () => {
    const before = readFileSync(auditOutputPath("file-size-baseline.json"), "utf8");
    const run = Bun.spawnSync(["bun", join(import.meta.dir, "check-file-size.ts"), "--init"], {
      stdout: "pipe",
      stderr: "pipe",
    });
    expect(run.exitCode).toBe(2);
    expect(run.stderr.toString()).toContain("refuses to replace");
    expect(readFileSync(auditOutputPath("file-size-baseline.json"), "utf8")).toBe(before);
  });
});
