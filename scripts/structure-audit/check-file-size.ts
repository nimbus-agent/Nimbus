#!/usr/bin/env bun
/**
 * File-size ratchet (owner ruling 2026-11-23: "never grow").
 *
 * A source or test file under `packages/` or `scripts/` stays under {@link LIMIT} lines. The files
 * that were already at or over it when the gate landed are listed, with their line count, in
 * `docs/structure-audit/file-size-baseline.json`, and that list only shrinks:
 *
 * - a file NOT in the baseline with {@link LIMIT} or more lines fails (new code is split up front);
 * - a baseline file that GREW past its recorded count fails, by any amount. A change that has to
 *   add lines to one first moves something out of it, in the same PR or an earlier one;
 * - a baseline entry that is stale (the file shrank, fell under the limit, or is gone) fails too,
 *   so the recorded counts follow every split down. `--update` writes the new counts and can only
 *   lower them: it never raises an entry or adds one.
 *
 * A rename of a baseline file is a hand edit of its key in the JSON, visible in review.
 * Generated files (first line `// GENERATED by ...`) and build output are not counted.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { auditOutputPath } from "./lib.ts";

export const LIMIT = 500;

const REPO_ROOT = join(import.meta.dir, "..", "..");
const BASELINE_PATH = auditOutputPath("file-size-baseline.json");

const COUNTED_EXTENSION = /\.(?:ts|tsx|mts|cts|js|mjs|cjs|rs)$/;
const SKIPPED_PATH = /(?:^|\/)(?:node_modules|dist|build|coverage|target|\.astro)\/|\.d\.ts$/;
const GENERATED_HEADER = /^\/\/ GENERATED by /;

export type Baseline = Readonly<Record<string, number>>;

export interface FileSize {
  readonly path: string;
  readonly lines: number;
}

export interface Verdict {
  /** New files at or over the limit. */
  readonly tooLarge: readonly FileSize[];
  /** Baseline files that grew past their recorded count. */
  readonly grew: ReadonlyArray<FileSize & { readonly baseline: number }>;
  /** Baseline entries whose file shrank, fell under the limit or is gone (`lines` 0 = gone). */
  readonly stale: ReadonlyArray<FileSize & { readonly baseline: number }>;
}

/** Lines as `wc -l` would count them, plus a final line with no newline. */
export function countLines(text: string): number {
  if (text.length === 0) return 0;
  let n = 0;
  for (let i = text.indexOf("\n"); i !== -1; i = text.indexOf("\n", i + 1)) n++;
  return text.endsWith("\n") ? n : n + 1;
}

export function isCounted(path: string, firstLine: string): boolean {
  if (!path.startsWith("packages/") && !path.startsWith("scripts/")) return false;
  if (!COUNTED_EXTENSION.test(path) || SKIPPED_PATH.test(path)) return false;
  return !GENERATED_HEADER.test(firstLine);
}

export function judge(sizes: readonly FileSize[], baseline: Baseline): Verdict {
  const byPath = new Map(sizes.map((s) => [s.path, s.lines]));
  const tooLarge: FileSize[] = [];
  const grew: Array<FileSize & { baseline: number }> = [];
  const stale: Array<FileSize & { baseline: number }> = [];
  for (const s of sizes) {
    const recorded = baseline[s.path];
    if (recorded === undefined) {
      if (s.lines >= LIMIT) tooLarge.push(s);
    } else if (s.lines > recorded) {
      grew.push({ ...s, baseline: recorded });
    }
  }
  for (const [path, recorded] of Object.entries(baseline)) {
    const lines = byPath.get(path) ?? 0;
    if (lines < recorded) stale.push({ path, lines, baseline: recorded });
  }
  const byLines = (a: FileSize, b: FileSize) => b.lines - a.lines || a.path.localeCompare(b.path);
  return { tooLarge: tooLarge.sort(byLines), grew: grew.sort(byLines), stale: stale.sort(byLines) };
}

/** The lowered baseline: stale entries take their new count, or leave when under the limit. */
export function lowered(sizes: readonly FileSize[], baseline: Baseline): Record<string, number> {
  const byPath = new Map(sizes.map((s) => [s.path, s.lines]));
  const next: Record<string, number> = {};
  for (const path of Object.keys(baseline).sort()) {
    const lines = byPath.get(path) ?? 0;
    const kept = Math.min(lines, baseline[path] ?? 0);
    if (kept >= LIMIT) next[path] = kept;
  }
  return next;
}

function listFiles(): string[] {
  const out = Bun.spawnSync(
    ["git", "ls-files", "--cached", "--others", "--exclude-standard", "--", "packages", "scripts"],
    { cwd: REPO_ROOT, stdout: "pipe", stderr: "pipe" },
  );
  if (out.exitCode !== 0) throw new Error(`git ls-files failed: ${out.stderr.toString()}`);
  return out.stdout.toString().split("\n").filter(Boolean);
}

export function measure(): FileSize[] {
  const sizes: FileSize[] = [];
  for (const path of listFiles()) {
    if (!COUNTED_EXTENSION.test(path) || SKIPPED_PATH.test(path)) continue;
    let text: string;
    try {
      text = readFileSync(join(REPO_ROOT, path), "utf8");
    } catch {
      continue; // deleted in the working tree but still in the index
    }
    if (!isCounted(path, text.split("\n", 1)[0] ?? "")) continue;
    sizes.push({ path, lines: countLines(text) });
  }
  return sizes;
}

function readBaseline(): Baseline {
  const parsed: unknown = JSON.parse(readFileSync(BASELINE_PATH, "utf8"));
  if (parsed === null || typeof parsed !== "object" || Array.isArray(parsed)) {
    throw new Error(`${BASELINE_PATH}: expected an object of path -> line count`);
  }
  const files = (parsed as { files?: unknown }).files;
  if (files === null || typeof files !== "object" || Array.isArray(files)) {
    throw new Error(`${BASELINE_PATH}: expected a "files" object`);
  }
  const out: Record<string, number> = {};
  for (const [k, v] of Object.entries(files)) {
    if (typeof v !== "number" || !Number.isInteger(v) || v < LIMIT) {
      throw new Error(`${BASELINE_PATH}: "${k}" must be an integer >= ${LIMIT}`);
    }
    out[k] = v;
  }
  return out;
}

function writeBaseline(files: Record<string, number>): void {
  const body = {
    $comment: `Files at or over ${LIMIT} lines when the file-size gate landed. Counts only go down: run \`bun run audit:file-size --update\` after a split. See scripts/structure-audit/check-file-size.ts.`,
    limit: LIMIT,
    files,
  };
  writeFileSync(BASELINE_PATH, `${JSON.stringify(body, null, 2)}\n`);
}

function main(argv: readonly string[]): number {
  const sizes = measure();
  if (argv.includes("--init")) {
    const files: Record<string, number> = {};
    for (const s of [...sizes].sort((a, b) => a.path.localeCompare(b.path))) {
      if (s.lines >= LIMIT) files[s.path] = s.lines;
    }
    writeBaseline(files);
    console.log(`file-size: wrote ${Object.keys(files).length} entries to ${BASELINE_PATH}`);
    return 0;
  }
  const baseline = readBaseline();
  if (argv.includes("--update")) {
    const next = lowered(sizes, baseline);
    writeBaseline(next);
    const dropped = Object.keys(baseline).length - Object.keys(next).length;
    console.log(
      `file-size: baseline lowered (${Object.keys(next).length} entries, ${dropped} removed)`,
    );
    const { tooLarge, grew } = judge(sizes, next);
    if (tooLarge.length + grew.length > 0) {
      console.error("file-size: --update lowers counts only; the failures below still stand.");
      return report({ tooLarge, grew, stale: [] });
    }
    return 0;
  }
  const verdict = judge(sizes, baseline);
  const over = sizes.filter((s) => s.lines >= LIMIT).length;
  if (verdict.tooLarge.length + verdict.grew.length + verdict.stale.length === 0) {
    console.log(`file-size: OK (${over} files at or over ${LIMIT} lines, none grew)`);
    return 0;
  }
  return report(verdict);
}

function report(v: Verdict): number {
  for (const f of v.tooLarge) {
    console.error(
      `::error file=${f.path}::${f.path} has ${f.lines} lines; new files stay under ${LIMIT}. Split it by phase or subsystem.`,
    );
  }
  for (const f of v.grew) {
    console.error(
      `::error file=${f.path}::${f.path} grew from ${f.baseline} to ${f.lines} lines. Files over ${LIMIT} lines never grow: move something out of it first.`,
    );
  }
  if (v.stale.length > 0) {
    for (const f of v.stale) {
      console.error(`  shrank: ${f.path} ${f.baseline} -> ${f.lines}`);
    }
    console.error(
      `::error::${v.stale.length} file-size baseline entr${v.stale.length === 1 ? "y is" : "ies are"} stale (good news). Run \`bun run audit:file-size --update\` and commit docs/structure-audit/file-size-baseline.json.`,
    );
  }
  return 1;
}

if (import.meta.main) process.exit(main(Bun.argv.slice(2)));
