/**
 * The Sigstore trusted roots baked into each release (offline provenance re-verification, owner
 * ruling OR-PROV-5): the two `trustedroot+json` documents `gh attestation trusted-root` prints, one
 * for public-good Sigstore and one for GitHub's own instance, kept byte for byte as one JSONL
 * string in a generated module. No runtime fetch, no TUF client: a root newer than the release is
 * unknown, and a bundle it signed reads "not re-verified".
 */

/** Repo-relative path of the generated module (forward slashes; join with the repo root). */
export const ROOTS_MODULE_REL =
  "packages/gateway/src/extensions/registry/sigstore-trusted-roots.ts";

const TRUSTED_ROOT_MEDIA_TYPE = "application/vnd.dev.sigstore.trustedroot+json;version=0.1";

/** The instance a trusted root belongs to, from its Fulcio certificate authorities' URIs. */
export type SigstoreInstance = "public-good" | "github";

const isObject = (v: unknown): v is Record<string, unknown> =>
  v !== null && typeof v === "object" && !Array.isArray(v);

function instanceOf(doc: Record<string, unknown>): SigstoreInstance | undefined {
  const cas = doc["certificateAuthorities"];
  if (!Array.isArray(cas) || cas.length === 0) return undefined;
  const uris = new Set(cas.map((c: unknown) => (isObject(c) ? c["uri"] : undefined)));
  if (uris.size !== 1) return undefined;
  const [uri] = [...uris];
  if (uri === "https://fulcio.sigstore.dev") return "public-good";
  if (uri === "fulcio.githubapp.com") return "github";
  return undefined;
}

const nonEmptyArray = (doc: Record<string, unknown>, key: string): boolean => {
  const v = doc[key];
  return Array.isArray(v) && v.length > 0;
};

/**
 * Checks `jsonl` is exactly two trusted-root documents, one per instance, each with the material
 * its verification needs (public-good: a transparency log and a CT log; GitHub: a timestamp
 * authority). Returns the instances in file order, or throws with what is wrong.
 */
export function validateTrustedRoots(jsonl: string): SigstoreInstance[] {
  const lines = jsonl.split("\n").filter((l) => l.trim() !== "");
  if (lines.length !== 2)
    throw new Error(`expected 2 trusted roots, found ${String(lines.length)}`);
  const seen: SigstoreInstance[] = [];
  for (const line of lines) {
    const doc: unknown = JSON.parse(line);
    if (!isObject(doc) || doc["mediaType"] !== TRUSTED_ROOT_MEDIA_TYPE) {
      throw new Error("a trusted root has an unknown media type");
    }
    const instance = instanceOf(doc);
    if (instance === undefined) throw new Error("a trusted root names an unknown Fulcio instance");
    if (
      instance === "public-good" &&
      !(nonEmptyArray(doc, "tlogs") && nonEmptyArray(doc, "ctlogs"))
    ) {
      throw new Error("the public-good root has no transparency or CT log");
    }
    if (instance === "github" && !nonEmptyArray(doc, "timestampAuthorities")) {
      throw new Error("the GitHub root has no timestamp authority");
    }
    if (seen.includes(instance)) throw new Error(`two trusted roots for ${instance}`);
    seen.push(instance);
  }
  return seen;
}

/** The generated module for `jsonl`. The audit re-renders it to prove the file was not hand-edited. */
export function renderRootsModule(jsonl: string): string {
  return [
    "// GENERATED by `bun run trust:refresh-sigstore-roots` (scripts/trust/refresh-sigstore-roots.ts).",
    "// Do not edit: `bun run audit:sigstore-roots` fails when this file is not what the script writes.",
    "//",
    "// The Sigstore trusted roots (`gh attestation trusted-root`: public-good and GitHub's instance),",
    "// byte for byte as JSONL, baked into the release for offline provenance re-verification",
    "// (owner ruling OR-PROV-5).",
    "// biome-ignore format: generated; the literal is JSON.stringify of the gh output",
    "export const BAKED_SIGSTORE_TRUSTED_ROOTS =",
    `  ${JSON.stringify(jsonl)};`,
    "",
  ].join("\n");
}
