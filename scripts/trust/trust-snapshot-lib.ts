/**
 * The baked trust-feed snapshot (marketplace trust layer PR 5): shared by the refresh script
 * (`bun run trust:refresh-snapshot`) and its audit (`bun run audit:trust-snapshot`).
 *
 * The snapshot is the live feed's `trust.json`, byte for byte, carried in a generated module so a
 * compiled binary has it. Every check here verifies against the BAKED root key
 * (`BUILTIN_TRUST_FEED.rootKey`), never the key a document names for itself: a feed signed by any
 * other key is refused, exactly as the gateway refuses it.
 */
import {
  MAX_TRUST_FEED_BYTES,
  parseTrustFeed,
  RegistryError,
  readTrustFeedStatements,
  type TrustFeed,
  trustFeedDigest,
  verifyTrustFeedPinned,
} from "../../packages/registry-format/src/index.ts";

export interface SnapshotFeedConfig {
  readonly url: string;
  readonly rootKey: string;
}

export type FetchFn = (url: string, init: RequestInit) => Promise<Response>;

/** Repo-relative path of the generated module (forward slashes; join with the repo root). */
export const SNAPSHOT_MODULE_REL = "packages/gateway/src/extensions/trust/trust-snapshot.ts";

export const LIVE_FETCH_TIMEOUT_MS = 30_000;

/** The generated module for a snapshot. The audit re-renders it to prove the file was not hand-edited. */
export function renderSnapshotModule(text: string): string {
  return [
    "// GENERATED by `bun run trust:refresh-snapshot` (scripts/trust/refresh-trust-snapshot.ts). Do not edit:",
    "// `bun run audit:trust-snapshot` fails when this file is not exactly what the script writes.",
    "//",
    "// The Nimbus trust feed's `trust.json`, byte for byte as it was served when the snapshot was",
    "// refreshed. The gateway applies it at boot as the offline floor (`BUILTIN_TRUST_SNAPSHOT`).",
    "// biome-ignore format: generated; the literal is JSON.stringify of the served bytes",
    "export const BAKED_TRUST_SNAPSHOT =",
    `  ${JSON.stringify(text)};`,
    "",
  ].join("\n");
}

/** A short description of an error for a finding line. */
function describe(e: unknown): string {
  if (e instanceof RegistryError) return `${e.code}: ${e.detail}`;
  return e instanceof Error ? e.message : String(e);
}

/**
 * Parses and verifies a feed document against the pinned root key, and requires every statement
 * to be readable by this version (none dropped, no unknown kind). Throws on any failure.
 */
export async function verifyFeedText(text: string, rootKey: string): Promise<TrustFeed> {
  const bytes = new TextEncoder().encode(text);
  if (bytes.byteLength > MAX_TRUST_FEED_BYTES) {
    throw new Error(
      `trust feed is ${bytes.byteLength} bytes, over the ${MAX_TRUST_FEED_BYTES} cap`,
    );
  }
  const feed = parseTrustFeed(bytes);
  await verifyTrustFeedPinned(feed, rootKey);
  const read = readTrustFeedStatements(feed);
  if (read.dropped > 0 || read.unknownKinds > 0) {
    throw new Error(
      `trust feed has ${read.dropped} malformed and ${read.unknownKinds} unknown-kind statement(s) this version cannot read`,
    );
  }
  return feed;
}

/** Where a feed stands against the baked snapshot. */
export type FeedComparison = "same" | "ahead" | "behind" | "equivocation";

export function compareFeeds(baked: TrustFeed, live: TrustFeed): FeedComparison {
  if (live.sequence > baked.sequence) return "ahead";
  if (live.sequence < baked.sequence) return "behind";
  return trustFeedDigest(live) === trustFeedDigest(baked) ? "same" : "equivocation";
}

/** Checks that the feed URL is one the gateway resolves `trust.json` against correctly. */
export function checkFeedUrl(url: string): string | null {
  let parsed: URL;
  try {
    parsed = new URL(url);
  } catch {
    return `trust feed URL is not a URL: ${url}`;
  }
  if (parsed.protocol !== "https:") return `trust feed URL is not https: ${url}`;
  // `new URL("trust.json", base)` drops the last path segment of a base without a trailing slash.
  if (!url.endsWith("/")) return `trust feed URL must end with "/": ${url}`;
  return null;
}

/**
 * The offline audit: everything that can be checked without the network. Returns one line per
 * problem; an empty list means the baked feed and snapshot are consistent.
 */
export async function checkBakedSnapshot(input: {
  readonly config: SnapshotFeedConfig | null;
  readonly snapshot: string | null;
  readonly moduleText: string;
}): Promise<string[]> {
  const { config, snapshot } = input;
  if (config === null) return ["BUILTIN_TRUST_FEED is null: this build follows no trust feed"];
  if (snapshot === null) return ["BUILTIN_TRUST_SNAPSHOT is null: this build carries no snapshot"];
  const findings: string[] = [];
  const urlProblem = checkFeedUrl(config.url);
  if (urlProblem !== null) findings.push(urlProblem);
  try {
    await verifyFeedText(snapshot, config.rootKey);
  } catch (e) {
    findings.push(`the baked snapshot does not verify against the baked root key (${describe(e)})`);
  }
  if (input.moduleText !== renderSnapshotModule(snapshot)) {
    findings.push(
      `${SNAPSHOT_MODULE_REL} is not what the refresh script writes: run \`bun run trust:refresh-snapshot\``,
    );
  }
  return findings;
}

/** Fetches the live `trust.json` (https only, capped, no redirects) and returns its text. */
export async function fetchLiveFeedText(
  config: SnapshotFeedConfig,
  fetchFn: FetchFn,
  timeoutMs: number = LIVE_FETCH_TIMEOUT_MS,
): Promise<string> {
  const urlProblem = checkFeedUrl(config.url);
  if (urlProblem !== null) throw new Error(urlProblem);
  const url = new URL("trust.json", config.url).href;
  const res = await fetchFn(url, { redirect: "error", signal: AbortSignal.timeout(timeoutMs) });
  if (!res.ok) throw new Error(`GET ${url} answered ${res.status}`);
  const bytes = new Uint8Array(await res.arrayBuffer());
  if (bytes.byteLength > MAX_TRUST_FEED_BYTES) {
    throw new Error(`GET ${url} returned ${bytes.byteLength} bytes, over the cap`);
  }
  return new TextDecoder("utf-8", { fatal: true }).decode(bytes);
}

/**
 * The live check: the live feed must verify and sit at the baked snapshot's sequence with the same
 * content. Returns one line per problem.
 */
export async function checkLiveFeed(input: {
  readonly config: SnapshotFeedConfig;
  readonly snapshot: string;
  readonly fetchFn: FetchFn;
}): Promise<string[]> {
  let baked: TrustFeed;
  let live: TrustFeed;
  try {
    baked = await verifyFeedText(input.snapshot, input.config.rootKey);
  } catch (e) {
    return [`the baked snapshot does not verify (${describe(e)})`];
  }
  try {
    live = await verifyFeedText(
      await fetchLiveFeedText(input.config, input.fetchFn),
      input.config.rootKey,
    );
  } catch (e) {
    return [`the live trust feed could not be read and verified (${describe(e)})`];
  }
  const verdict = compareFeeds(baked, live);
  if (verdict === "same") return [];
  const findings: Record<Exclude<FeedComparison, "same">, string> = {
    ahead: `the snapshot is stale: the live feed is at sequence ${live.sequence}, the baked snapshot at ${baked.sequence}. Run \`bun run trust:refresh-snapshot\` and open a PR.`,
    behind: `the live feed went BACKWARDS: sequence ${live.sequence} is below the baked ${baked.sequence}. Every gateway refuses it; check the nimbus-trust gh-pages branch.`,
    equivocation: `the live feed and the baked snapshot are both sequence ${live.sequence} with different content. Every gateway that saw the other copy refuses this one; investigate before refreshing.`,
  };
  return [findings[verdict]];
}

export type RefreshOutcome =
  | { readonly kind: "unchanged"; readonly sequence: number }
  | { readonly kind: "updated"; readonly from: number; readonly to: number; readonly text: string };

/**
 * Decides what the refresh script writes: the live text when it is verified and ahead of the
 * baked snapshot; nothing when it is the same document. Refuses a rollback or an equivocation, and
 * (with no verifiable baked snapshot) accepts any live feed that verifies against the baked key.
 */
export async function planRefresh(input: {
  readonly config: SnapshotFeedConfig;
  readonly snapshot: string | null;
  readonly liveText: string;
}): Promise<RefreshOutcome> {
  const live = await verifyFeedText(input.liveText, input.config.rootKey);
  if (input.snapshot === null) {
    return { kind: "updated", from: 0, to: live.sequence, text: input.liveText };
  }
  const baked = await verifyFeedText(input.snapshot, input.config.rootKey);
  const verdict = compareFeeds(baked, live);
  if (verdict === "same") return { kind: "unchanged", sequence: baked.sequence };
  if (verdict === "ahead") {
    return { kind: "updated", from: baked.sequence, to: live.sequence, text: input.liveText };
  }
  throw new Error(
    verdict === "behind"
      ? `refusing a rollback: live sequence ${live.sequence} is below the baked ${baked.sequence}`
      : `refusing an equivocation: live sequence ${live.sequence} has different content from the baked snapshot`,
  );
}
