import { posix } from "node:path";

export interface RpmSpecInputs {
  /** Semver without a leading "v". */
  version: string;
  /** Directory holding the staged `nimbus`, `nimbus-gateway` and `nimbus-sandbox-helper`. */
  binDir: string;
  /** Directory holding the generated `/usr/local/bin` wrapper scripts (`nimbus`, `nimbus-gateway`). */
  wrapperDir: string;
  /**
   * `binDir` also holds the sqlite-vec extension `vec0.so`. The gateway loads it from beside its own
   * executable, so it ships at the same relative place as in the `.deb` and the tarball. A bundle
   * built where `bun install` skipped the platform binary has none, and then the package has no
   * semantic search, as it does not on the other formats.
   */
  hasVec0?: boolean;
}

/**
 * zstd level 19 with a 128 MiB window. The gateway and the CLI each embed the Bun runtime, and only a
 * window that wide sees the second copy as a repeat of the first. On v10.14.0 this made a 48.7 MiB
 * package, against 89.4 MiB at level 19 alone and the 117.9 MiB gzip package that release shipped. The apt/yum repo is a Git
 * repository, where a file over 100 MiB is refused. 128 MiB is the widest window a zstd decoder
 * accepts by default, so `rpm` needs no option to read it. It needs rpm 4.14 or later.
 */
export const RPM_BINARY_PAYLOAD = "w19L27.zstdio";

/** RPM forbids `-` in a version. `~` is the same pre-release, and sorts before the final release. */
export function rpmVersion(version: string): string {
  return version.replaceAll("-", "~");
}

/**
 * Render the spec `rpmbuild` packages the Nimbus headless bundle from. Mirrors the bespoke `.deb`
 * layout in package-linux-installers.ts: real binaries under /usr/lib/nimbus/bin, thin wrappers in
 * /usr/local/bin, a bubblewrap dependency, and the sandbox helper with no file capability and no
 * setuid bit.
 *
 * `__os_install_post` is emptied because its default strips binaries, and a compiled Bun binary
 * carries its program after the ELF sections. `AutoReqProv` is off so bubblewrap stays the only
 * dependency.
 *
 * Pure: paths are interpolated, no filesystem access. The caller writes the spec and invokes
 * `rpmbuild`.
 */
export function renderRpmSpec(i: RpmSpecInputs): string {
  const files: { src: string; dst: string; mode: string }[] = [
    {
      src: posix.join(i.binDir, "nimbus-gateway"),
      dst: "/usr/lib/nimbus/bin/nimbus-gateway",
      mode: "0755",
    },
    { src: posix.join(i.binDir, "nimbus"), dst: "/usr/lib/nimbus/bin/nimbus", mode: "0755" },
    { src: posix.join(i.wrapperDir, "nimbus"), dst: "/usr/local/bin/nimbus", mode: "0755" },
    {
      src: posix.join(i.wrapperDir, "nimbus-gateway"),
      dst: "/usr/local/bin/nimbus-gateway",
      mode: "0755",
    },
    {
      src: posix.join(i.binDir, "nimbus-sandbox-helper"),
      dst: "/usr/lib/nimbus/bin/nimbus-sandbox-helper",
      mode: "0755",
    },
  ];
  if (i.hasVec0 === true) {
    // 0644, like the file in the `.deb`: it is loaded, never executed.
    files.push({
      src: posix.join(i.binDir, "vec0.so"),
      dst: "/usr/lib/nimbus/bin/vec0.so",
      mode: "0644",
    });
  }

  return `# Generated by scripts/release/rpm-spec.ts — do not edit by hand.
%global debug_package %{nil}
%global __os_install_post %{nil}
%global _build_id_links none
%global _binary_payload ${RPM_BINARY_PAYLOAD}
Name: nimbus-headless
Version: ${rpmVersion(i.version)}
Release: 1
Summary: Nimbus CLI and headless Gateway (local-first agent framework)
License: AGPL-3.0-only
URL: https://github.com/nimbus-agent/Nimbus
Packager: Nimbus Contributors <https://github.com/nimbus-agent/Nimbus>
AutoReqProv: no
Requires: bubblewrap

%description
Nimbus CLI and headless Gateway (local-first agent framework).

%install
${files.map((f) => `install -D -m ${f.mode} '${f.src}' '%{buildroot}${f.dst}'`).join("\n")}

%files
${files.map((f) => `%attr(${f.mode},root,root) ${f.dst}`).join("\n")}
`;
}
