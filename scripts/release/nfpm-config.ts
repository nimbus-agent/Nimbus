import { posix } from "node:path";

export interface NfpmInputs {
  /** Semver without a leading "v". */
  version: string;
  /** Directory holding the staged `nimbus`, `nimbus-gateway` and `nimbus-sandbox-helper`. */
  binDir: string;
  /** Directory holding the generated `/usr/local/bin` wrapper scripts (`nimbus`, `nimbus-gateway`). */
  wrapperDir: string;
  /**
   * `binDir` also holds the sqlite-vec extension `vec0.so`. The gateway loads it from beside its own
   * executable, so it ships at the same relative place as in the `.deb` and the tarball. A bundle
   * built where `bun install` skipped the platform binary has none, and then the package has no
   * semantic search, as it does not on the other formats.
   */
  hasVec0?: boolean;
}

/**
 * Render an nfpm v2 config that packages the Nimbus headless bundle as an `.rpm`
 * (and could emit a `.deb` from the same config). Mirrors the bespoke `.deb`
 * layout in package-linux-installers.ts: real binaries under /usr/lib/nimbus/bin,
 * thin wrappers in /usr/local/bin, a bubblewrap dependency, and the sandbox helper with no file
 * capability and no setuid bit.
 *
 * Pure: paths are interpolated, no filesystem access. The caller writes the YAML
 * and invokes `nfpm package`.
 */
export function renderNfpmConfig(i: NfpmInputs): string {
  const contents: string[] = [
    `  - src: ${posix.join(i.binDir, "nimbus-gateway")}`,
    `    dst: /usr/lib/nimbus/bin/nimbus-gateway`,
    `    file_info:\n      mode: 0755`,
    `  - src: ${posix.join(i.binDir, "nimbus")}`,
    `    dst: /usr/lib/nimbus/bin/nimbus`,
    `    file_info:\n      mode: 0755`,
    `  - src: ${posix.join(i.wrapperDir, "nimbus")}`,
    `    dst: /usr/local/bin/nimbus`,
    `    file_info:\n      mode: 0755`,
    `  - src: ${posix.join(i.wrapperDir, "nimbus-gateway")}`,
    `    dst: /usr/local/bin/nimbus-gateway`,
    `    file_info:\n      mode: 0755`,
    `  - src: ${posix.join(i.binDir, "nimbus-sandbox-helper")}`,
    `    dst: /usr/lib/nimbus/bin/nimbus-sandbox-helper`,
    `    file_info:\n      mode: 0755`,
  ];
  if (i.hasVec0 === true) {
    // 0644, like the file in the `.deb`: it is loaded, never executed.
    contents.push(
      `  - src: ${posix.join(i.binDir, "vec0.so")}`,
      `    dst: /usr/lib/nimbus/bin/vec0.so`,
      `    file_info:\n      mode: 0644`,
    );
  }

  return `# Generated by scripts/release/nfpm-config.ts — do not edit by hand.
name: nimbus-headless
arch: amd64
version: ${i.version}
maintainer: Nimbus Contributors <https://github.com/nimbus-agent/Nimbus>
description: Nimbus CLI and headless Gateway (local-first agent framework)
homepage: https://github.com/nimbus-agent/Nimbus
license: AGPL-3.0-only
section: utils
priority: optional
overrides:
  rpm:
    depends:
      - bubblewrap
  deb:
    depends:
      - bubblewrap
contents:
${contents.join("\n")}
`;
}
