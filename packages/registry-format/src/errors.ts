/** A registry refusal. The code leads the message, so a CLI shows it; `detail` is the rest. */
export class RegistryError extends Error {
  constructor(
    readonly code: RegistryErrorCode,
    readonly detail: string,
  ) {
    super(`${code}: ${detail}`);
    this.name = "RegistryError";
  }
}
