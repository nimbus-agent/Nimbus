import { describe, expect, test } from "bun:test";

import {
  esc,
  type PageDoraCell,
  renderStatuspageHtml,
  type StatuspagePageModel,
  safeHref,
} from "./statuspage-render.ts";

const NOW = Date.UTC(2026, 10, 16, 9, 0);
const NO_DATA: PageDoraCell = { value: null, unit: "deploys_per_day", sample: 0, gap: "no_repos" };

function model(over: Partial<StatuspagePageModel> = {}): StatuspagePageModel {
  return {
    generatedAtMs: NOW,
    generatedAt: new Date(NOW).toISOString(),
    options: { services: [], titles: false, links: false },
    incidents: { status: "none_open", total: 0, items: [], sources: [] },
    onCall: { status: "ok", shifts: [], next: [], sources: [] },
    dora: { status: "ok", windowDays: 30, rows: [] },
    gaps: [],
    ...over,
  };
}

describe("esc", () => {
  test("neutralises markup and attribute breakers", () => {
    const out = esc(`<script>alert("x")</script> ' \` &`);
    expect(out).not.toContain("<");
    expect(out).not.toContain(">");
    expect(out).not.toContain('"');
    expect(out).not.toContain("'");
    expect(out).toBe("&lt;script&gt;alert(&quot;x&quot;)&lt;/script&gt; &#39; &#96; &amp;");
  });

  test("an attribute-breaking value stays inside its quotes", () => {
    const html = `<a href="${esc('x" onmouseover="alert(1)')}">`;
    expect(html).toBe('<a href="x&quot; onmouseover=&quot;alert(1)">');
  });

  test("control, bidi-override and separator characters become a space", () => {
    expect(esc("a\u0000b\u001bc\nd\u202ee\u2028f\u0085g\u007fh")).toBe("a b c d e f g h");
  });

  test("non-strings are stringified", () => {
    expect(esc(42)).toBe("42");
  });
});

describe("safeHref", () => {
  test("only http(s) survives", () => {
    expect(safeHref("https://a.test/x")).toBe("https://a.test/x");
    expect(safeHref("javascript:alert(1)")).toBeUndefined();
    expect(safeHref("data:text/html,x")).toBeUndefined();
    expect(safeHref("/relative")).toBeUndefined();
    expect(safeHref(undefined)).toBeUndefined();
  });
});

describe("renderStatuspageHtml", () => {
  test("has the banner, the comment, inline CSS only and no script or external resource", () => {
    const html = renderStatuspageHtml(model());
    expect(
      html.startsWith(
        "<!doctype html>\n<!-- Draft generated by Nimbus on 2026-11-16. Review before publishing.",
      ),
    ).toBe(true);
    expect(html).toContain('class="draft-banner"');
    expect(html).toContain("Draft generated by Nimbus on 2026-11-16. Review before publishing.");
    expect(html).not.toMatch(/<script/i);
    expect(html).not.toMatch(/<link\b/i);
    expect(html).not.toMatch(/<img\b/i);
    expect(html).not.toMatch(/\bsrc=/i);
    expect(html).not.toMatch(/@import|url\(/i);
    expect(html).toContain("default-src 'none'");
  });

  test("no data and no open incidents read differently", () => {
    const none = renderStatuspageHtml(model());
    expect(none).toContain("No open incidents");
    const noData = renderStatuspageHtml(
      model({ incidents: { status: "no_data", total: 0, items: [], sources: [] } }),
    );
    expect(noData).not.toContain("No open incidents");
    expect(noData).toContain("no incident data is indexed");
  });

  test("an incident shows a short id, status, severity and service, but no title or link by default", () => {
    const html = renderStatuspageHtml(
      model({
        incidents: {
          status: "open",
          total: 1,
          sources: [
            { source: "pagerduty", indexed: true, lastSyncMs: NOW - 60_000, stale: false, open: 1 },
            { source: "jsm", indexed: false, lastSyncMs: null, stale: false, open: 0 },
          ],
          items: [
            {
              kind: "pagerduty_incident",
              ref: "PA1",
              status: "triggered",
              severity: "P1",
              urgency: "high",
              service: "payments",
              openedAtMs: NOW - 3_600_000,
            },
          ],
        },
      }),
    );
    expect(html).toContain("Incident PA1");
    expect(html).toContain("triggered");
    expect(html).toContain("P1, high urgency");
    expect(html).toContain("payments");
    expect(html).toContain("PagerDuty: synced");
    expect(html).toContain("Jira Service Management: not indexed");
    expect(html).not.toContain('class="title"');
    expect(html).not.toContain("<a ");
  });

  test("titles and links render escaped, and a javascript: link never becomes an anchor", () => {
    const item = {
      kind: "pagerduty_incident" as const,
      ref: "PA1",
      status: "triggered",
      severity: null,
      urgency: null,
      service: null,
      openedAtMs: null,
      title: '<img src=x onerror=alert(1)> "q"',
    };
    const html = renderStatuspageHtml(
      model({
        options: { services: [], titles: true, links: true },
        incidents: {
          status: "open",
          total: 2,
          sources: [],
          items: [
            { ...item, url: 'https://a.test/i?x="1"&y=<2>' },
            { ...item, ref: "PA2", url: "javascript:alert(1)" },
          ],
        },
      }),
    );
    expect(html).not.toContain("<img");
    expect(html).toContain("&lt;img src=x onerror=alert(1)&gt; &quot;q&quot;");
    expect(html).toContain(
      '<a href="https://a.test/i?x=%221%22&amp;y=%3C2%3E" rel="noopener noreferrer">',
    );
    expect(html).not.toContain("javascript:");
    expect(html).toContain("unbound");
    expect(html).toContain("unknown");
  });

  test("a hostile service id, title and gap are escaped everywhere they appear", () => {
    const evil = "<script>alert(1)</script>";
    const html = renderStatuspageHtml(
      model({
        options: { services: [evil], titles: false, links: false },
        dora: {
          status: "ok",
          windowDays: 30,
          rows: [
            {
              service: evil,
              deployment_frequency: NO_DATA,
              lead_time_for_changes: NO_DATA,
              change_failure_rate: NO_DATA,
              mttr: NO_DATA,
            },
          ],
        },
        gaps: [evil],
      }),
      { title: evil },
    );
    expect(html).not.toContain("<script");
    expect(html).toContain("&lt;script&gt;alert(1)&lt;/script&gt;");
    expect(html).toContain("<title>&lt;script&gt;");
  });

  test("on call: a name, 'on call' when only an e-mail was known, and the unknown states", () => {
    const shift = {
      source: "pagerduty" as const,
      schedule: "Payments primary",
      policy: null,
      level: 1,
      startMs: null,
      endMs: NOW + 3_600_000,
    };
    const ok = renderStatuspageHtml(
      model({
        onCall: {
          status: "ok",
          shifts: [
            { ...shift, name: "Alice Ng" },
            { ...shift, schedule: null, name: null },
          ],
          next: [{ ...shift, name: "Bob" }],
          sources: [],
        },
      }),
    );
    expect(ok).toContain("Payments primary</span>: Alice Ng until 2026-11-16 10:00 UTC");
    expect(ok).toContain("On-call</span>: on call");
    expect(ok).toContain("<h3>Next</h3>");
    for (const status of ["no_data", "no_match", "none_on_call"] as const) {
      const html = renderStatuspageHtml(
        model({ onCall: { status, shifts: [], next: [], sources: [] } }),
      );
      expect(html).toMatch(/Unknown:|No on-call shift covers/);
    }
  });

  test("DORA: values are formatted with their sample, missing values say 'No data' with the reason", () => {
    const html = renderStatuspageHtml(
      model({
        dora: {
          status: "ok",
          windowDays: 30,
          rows: [
            {
              service: "payments",
              deployment_frequency: { value: 1.5, unit: "deploys_per_day", sample: 45, gap: null },
              lead_time_for_changes: {
                value: 7200,
                unit: "seconds_median",
                sample: 2,
                gap: "low_sample",
              },
              change_failure_rate: { value: 0.125, unit: "ratio", sample: 8, gap: null },
              mttr: NO_DATA,
            },
          ],
        },
      }),
    );
    expect(html).toContain("1.50 per day");
    expect(html).toContain("2.0 h (median)");
    expect(html).toContain("12.5%");
    expect(html).toContain("n=2, low sample");
    expect(html).toContain("No data");
    expect(html).toContain("no repositories are bound");
    expect(html).toContain("Computed over the last 30 days.");
  });

  test("DORA unknown states and the duration ladder", () => {
    for (const status of ["no_services", "config_error"] as const) {
      expect(renderStatuspageHtml(model({ dora: { status, windowDays: 30, rows: [] } }))).toContain(
        "Unknown:",
      );
    }
    const cell = (v: number): PageDoraCell => ({
      value: v,
      unit: "seconds_median",
      sample: 5,
      gap: null,
    });
    const html = renderStatuspageHtml(
      model({
        dora: {
          status: "ok",
          windowDays: 30,
          rows: [
            {
              service: "s",
              deployment_frequency: { value: 2, unit: "weird", sample: 5, gap: "unlisted_gap" },
              lead_time_for_changes: cell(30),
              change_failure_rate: cell(600),
              mttr: cell(5 * 86_400),
            },
          ],
        },
      }),
    );
    expect(html).toContain("30 s (median)");
    expect(html).toContain("10 min (median)");
    expect(html).toContain("5.0 days (median)");
    expect(html).toContain("2 weird");
    expect(html).toContain("unlisted gap");
  });

  test("the footer says when and from what, lists gaps, and says so when there are none", () => {
    const withGaps = renderStatuspageHtml(model({ gaps: ["Something is missing."] }));
    expect(withGaps).toContain("Generated <time");
    expect(withGaps).toContain("local index");
    expect(withGaps).toContain("<li>Something is missing.</li>");
    expect(renderStatuspageHtml(model())).toContain("No gaps were found");
    const scoped = renderStatuspageHtml(
      model({ options: { services: ["a", "b"], titles: false, links: false } }),
    );
    expect(scoped).toContain("services: a, b");
  });

  test("a truncated incident list says how many are shown, and a stale source is flagged", () => {
    const html = renderStatuspageHtml(
      model({
        incidents: {
          status: "open",
          total: 150,
          sources: [{ source: "pagerduty", indexed: true, lastSyncMs: null, stale: true, open: 1 }],
          items: [
            {
              kind: "jsm_alert",
              ref: "A1",
              status: null,
              severity: null,
              urgency: null,
              service: null,
              openedAtMs: null,
            },
          ],
        },
      }),
    );
    expect(html).toContain("Showing 1 of 150.");
    expect(html).toContain("last sync unknown (may be out of date)");
    expect(html).toContain("Alert A1");
  });
});
